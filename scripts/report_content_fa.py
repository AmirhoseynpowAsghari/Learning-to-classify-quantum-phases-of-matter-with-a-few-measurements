# -*- coding: utf-8 -*-
"""
Persian-language content for the presentation report, as an ordered list of
block tuples consumed by generate_persian_report.py.

Block types:
  ("h1", title)                                  chapter heading (new page)
  ("h2", title)                                  sub-heading
  ("h3", title)                                  sub-sub-heading
  ("p", text)                                    body paragraph (justified, RTL)
  ("p_ltr", text)                                 LTR paragraph, no Arabic shaping (e.g. citation)
  ("bullets", [items])                           bullet list
  ("numbered", [items])                          numbered list (Persian digits)
  ("formula", image_path, caption_or_None)       centered formula image
  ("figure", image_path, caption, width_mm)      centered figure + caption
  ("code", text)                                 LTR monospace code block
  ("table", headers, rows)                       simple bordered table
  ("space", mm)
  ("hr",)                                        thin horizontal rule
"""

FORMULAS = "assets/formulas"
FIGURES = "figures"

CONTENT = []


def H1(t):
    CONTENT.append(("h1", t))


def H2(t):
    CONTENT.append(("h2", t))


def H3(t):
    CONTENT.append(("h3", t))


def P(t):
    CONTENT.append(("p", t))


def BULLETS(items):
    CONTENT.append(("bullets", items))


def NUMBERED(items):
    CONTENT.append(("numbered", items))


def FORMULA(name, caption=None):
    CONTENT.append(("formula", f"{FORMULAS}/{name}.png", caption))


def FIGURE(name, caption, width_mm=150):
    CONTENT.append(("figure", f"{FIGURES}/{name}.png", caption, width_mm))


def CODE(t):
    CONTENT.append(("code", t))


def TABLE(headers, rows):
    CONTENT.append(("table", headers, rows))


def MONO_LINE(text):
    """A single LTR line (URL/path), auto-shrunk to fit the content width."""
    CONTENT.append(("mono_line", text))


def P_LTR(text):
    """A left-to-right, multi-line paragraph (e.g. an English citation)
    rendered without Arabic/RTL shaping. Needed because a wrapped line of a
    shaped RTL multi_cell that ends up being pure-Latin/numeric (no Arabic
    anchor characters) can trigger a reproducible fpdf2 glyph-corruption bug.
    """
    CONTENT.append(("p_ltr", text))


def SPACE(mm=4):
    CONTENT.append(("space", mm))


def HR():
    CONTENT.append(("hr",))


